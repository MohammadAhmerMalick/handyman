import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '../..')
const i18nDir = path.join(root, 'src/data/services/i18n')
const locales = ['ar', 'ur', 'hi', 'zh', 'fr']
const sourceDir = path.join(root, 'tmp/i18n/source')
const categories = existsSync(sourceDir)
  ? readdirSync(sourceDir)
      .filter((file) => file.endsWith('.json'))
      .map((file) => file.replace(/\.json$/, ''))
      .sort()
  : []

mkdirSync(i18nDir, { recursive: true })

const imports = []
const localeBlocks = []
let importIndex = 0

for (const locale of locales) {
  const entries = []
  for (const category of categories) {
    const rel = `./${locale}/${category}.json`
    const abs = path.join(i18nDir, locale, `${category}.json`)
    if (!existsSync(abs)) continue
    const ident = `t${importIndex}`
    importIndex += 1
    imports.push(`import ${ident} from '${rel}'`)
    entries.push(`    '${category}': ${ident},`)
  }
  localeBlocks.push(`  ${locale}: {\n${entries.join('\n')}\n  },`)
}

const contents = `// Generated by tmp/i18n/generate-registry.mjs — do not edit by hand.
import type { ServiceSeed } from '@/data/services/buildService'
import type { AppLocale } from '@/i18n/routing'

export type ServiceOverlay = Pick<
  ServiceSeed,
  | 'angle'
  | 'benefits'
  | 'includes'
  | 'outcome'
  | 'problems'
  | 'tips'
  | 'title'
  | 'whenNeeded'
> & {
  complianceNote?: string
}

export type OverlayBundle = Record<string, Record<string, ServiceOverlay>>

${imports.join('\n')}

export const overlays: Partial<Record<AppLocale, OverlayBundle>> = {
${localeBlocks.join('\n')}
}
`

writeFileSync(path.join(i18nDir, 'registry.ts'), `${contents.trim()}\n`)
console.log(`Wrote registry with ${importIndex} JSON imports`)
